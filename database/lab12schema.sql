-- PostgreSQL-only optional Lab 12 capstone schema.
-- Creates AIHR_EMPLOYEE_ASSESSMENTS as a source reference for the Lab 12 assessment build.

DROP TABLE IF EXISTS aihr_employee_assessments CASCADE;

CREATE TABLE aihr_employee_assessments (
    assessment_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    employee_id integer NOT NULL,
    cycle_code varchar(30) NOT NULL,
    review_status varchar(20) DEFAULT 'DRAFT' NOT NULL,
    goal_completion_pct numeric(5,2) NOT NULL,
    competency_score numeric(4,2) NOT NULL,
    manager_feedback text NOT NULL,
    employee_reflection text,
    next_cycle_plan text NOT NULL,
    reviewer_user_id integer NOT NULL,
    submitted_at timestamp,
    created_at timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT aihr_employee_assessments_pk PRIMARY KEY (assessment_id),
    CONSTRAINT aihr_employee_assessments_employee_fk FOREIGN KEY (employee_id) REFERENCES aihr_employees(employee_id),
    CONSTRAINT aihr_employee_assessments_cycle_fk FOREIGN KEY (cycle_code) REFERENCES aihr_assessment_cycles(cycle_code),
    CONSTRAINT aihr_employee_assessments_reviewer_fk FOREIGN KEY (reviewer_user_id) REFERENCES aihr_users(user_id),
    CONSTRAINT aihr_employee_assessments_cycle_uk UNIQUE (employee_id, cycle_code),
    CONSTRAINT aihr_employee_assessments_goal_pct_ck CHECK (goal_completion_pct BETWEEN 0 AND 100),
    CONSTRAINT aihr_employee_assessments_comp_score_ck CHECK (competency_score BETWEEN 0 AND 5),
    CONSTRAINT aihr_employee_assessments_status_ck CHECK (review_status IN ('DRAFT', 'SUBMITTED', 'FINAL'))
);

COMMENT ON TABLE aihr_employee_assessments IS 'Optional Lab 12 capstone table for employee performance assessments. Not part of the core runtime until the capstone is implemented.';
COMMENT ON COLUMN aihr_employee_assessments.cycle_code IS 'Assessment-cycle business key such as FY2026-H1.';
COMMENT ON COLUMN aihr_employee_assessments.goal_completion_pct IS 'Objective progress metric expressed as a percentage from 0 to 100.';
COMMENT ON COLUMN aihr_employee_assessments.competency_score IS 'Normalized performance score from 0.00 to 5.00.';
COMMENT ON COLUMN aihr_employee_assessments.manager_feedback IS 'Manager or HR narrative feedback for the cycle.';
COMMENT ON COLUMN aihr_employee_assessments.employee_reflection IS 'Optional employee self-reflection or response notes.';
COMMENT ON COLUMN aihr_employee_assessments.next_cycle_plan IS 'Future-planning notes and goals for the next cycle.';
COMMENT ON COLUMN aihr_employee_assessments.review_status IS 'Capstone-friendly workflow state: DRAFT, SUBMITTED, or FINAL.';

CREATE INDEX aihr_emp_assessments_reviewer_ix ON aihr_employee_assessments(reviewer_user_id);
CREATE INDEX aihr_emp_assessments_status_ix ON aihr_employee_assessments(review_status, updated_at);
