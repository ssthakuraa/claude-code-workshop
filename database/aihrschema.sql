DECLARE
    PROCEDURE drop_table_if_exists(p_table_name IN VARCHAR2) IS
        l_count NUMBER;
    BEGIN
        SELECT COUNT(*)
          INTO l_count
          FROM user_tables
         WHERE table_name = UPPER(p_table_name);

        IF l_count > 0 THEN
            EXECUTE IMMEDIATE 'DROP TABLE ' || p_table_name || ' CASCADE CONSTRAINTS PURGE';
        END IF;
    END;
BEGIN
    drop_table_if_exists('aihr_pay_grades');
    drop_table_if_exists('aihr_idempotency_keys');
    drop_table_if_exists('aihr_notifications');
    drop_table_if_exists('aihr_employee_documents');
    drop_table_if_exists('aihr_audit_logs');
    drop_table_if_exists('aihr_user_preferences');
    drop_table_if_exists('aihr_user_roles');
    drop_table_if_exists('aihr_users');
    drop_table_if_exists('aihr_roles');
    drop_table_if_exists('aihr_job_history');
    drop_table_if_exists('aihr_employees');
    drop_table_if_exists('aihr_departments');
    drop_table_if_exists('aihr_locations');
    drop_table_if_exists('aihr_countries');
    drop_table_if_exists('aihr_jobs');
    drop_table_if_exists('aihr_regions');
END;
/

CREATE TABLE aihr_regions (
    region_id NUMBER(10) NOT NULL,
    region_name VARCHAR2(25 CHAR),
    CONSTRAINT regions_pk PRIMARY KEY (region_id)
);

COMMENT ON TABLE aihr_regions IS 'Regions table that contains region numbers and names. References with the Countries table.';

CREATE TABLE aihr_countries (
    country_id CHAR(2 CHAR) NOT NULL,
    country_name VARCHAR2(60 CHAR),
    region_id NUMBER(10),
    CONSTRAINT countries_pk PRIMARY KEY (country_id),
    CONSTRAINT countries_region_fk FOREIGN KEY (region_id) REFERENCES aihr_regions(region_id)
);

COMMENT ON TABLE aihr_countries IS 'Country table. References with the aihr_locations table.';

CREATE TABLE aihr_locations (
    location_id NUMBER(10) NOT NULL,
    street_address VARCHAR2(40 CHAR),
    postal_code VARCHAR2(12 CHAR),
    city VARCHAR2(30 CHAR) NOT NULL,
    state_province VARCHAR2(25 CHAR),
    country_id CHAR(2 CHAR),
    CONSTRAINT locations_pk PRIMARY KEY (location_id),
    CONSTRAINT locations_country_fk FOREIGN KEY (country_id) REFERENCES aihr_countries(country_id)
);

COMMENT ON TABLE aihr_locations IS 'Locations table that contains specific address of a specific office, warehouse, and/or production site of a company.';

CREATE TABLE aihr_departments (
    department_id NUMBER(10) NOT NULL,
    department_name VARCHAR2(30 CHAR) NOT NULL,
    manager_id NUMBER(10),
    location_id NUMBER(10),
    parent_department_id NUMBER(10),
    deleted_at TIMESTAMP,
    CONSTRAINT departments_pk PRIMARY KEY (department_id),
    CONSTRAINT departments_location_fk FOREIGN KEY (location_id) REFERENCES aihr_locations(location_id),
    CONSTRAINT dept_parent_fk FOREIGN KEY (parent_department_id) REFERENCES aihr_departments(department_id)
);

COMMENT ON TABLE aihr_departments IS 'Departments table that shows details of departments where employees work.';

CREATE TABLE aihr_jobs (
    job_id VARCHAR2(10 CHAR) NOT NULL,
    job_title VARCHAR2(35 CHAR) NOT NULL,
    min_salary NUMBER(10),
    max_salary NUMBER(10),
    CONSTRAINT jobs_pk PRIMARY KEY (job_id)
);

COMMENT ON TABLE aihr_jobs IS 'Jobs table with job titles and salary ranges. References with aihr_employees and aihr_job_history table.';

CREATE TABLE aihr_pay_grades (
    pay_grade_id NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    grade_code VARCHAR2(20 CHAR) NOT NULL,
    grade_name VARCHAR2(60 CHAR) NOT NULL,
    min_salary NUMBER(10,2) NOT NULL,
    max_salary NUMBER(10,2) NOT NULL,
    currency_code VARCHAR2(3 CHAR) DEFAULT 'USD' NOT NULL,
    display_order NUMBER(4) NOT NULL,
    description VARCHAR2(255 CHAR),
    is_active NUMBER(1) DEFAULT 1 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT aihr_pay_grades_pk PRIMARY KEY (pay_grade_id),
    CONSTRAINT aihr_pay_grades_code_uk UNIQUE (grade_code),
    CONSTRAINT aihr_pay_grades_range_ck CHECK (max_salary >= min_salary),
    CONSTRAINT aihr_pay_grades_active_ck CHECK (is_active IN (0, 1))
);

COMMENT ON TABLE aihr_pay_grades IS 'Lab-only reference table for salary bands and pay-grade exercises. No backend resource or service is planned in the current phase.';

CREATE TABLE aihr_employees (
    employee_id NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 207) NOT NULL,
    first_name VARCHAR2(20 CHAR),
    last_name VARCHAR2(25 CHAR) NOT NULL,
    email VARCHAR2(100 CHAR) NOT NULL,
    phone_number VARCHAR2(20 CHAR),
    hire_date DATE NOT NULL,
    job_id VARCHAR2(10 CHAR) NOT NULL,
    salary NUMBER(8,2),
    commission_pct NUMBER(3,2),
    manager_id NUMBER(10),
    department_id NUMBER(10),
    employment_status VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    employment_type VARCHAR2(20 CHAR) DEFAULT 'FULL_TIME' NOT NULL,
    contract_end_date DATE,
    deleted_at TIMESTAMP,
    CONSTRAINT employees_pk PRIMARY KEY (employee_id),
    CONSTRAINT employees_email_uk UNIQUE (email),
    CONSTRAINT employees_department_fk FOREIGN KEY (department_id) REFERENCES aihr_departments(department_id),
    CONSTRAINT employees_job_fk FOREIGN KEY (job_id) REFERENCES aihr_jobs(job_id),
    CONSTRAINT employees_manager_fk FOREIGN KEY (manager_id) REFERENCES aihr_employees(employee_id),
    CONSTRAINT employees_salary_ck CHECK (salary > 0),
    CONSTRAINT employees_status_ck CHECK (employment_status IN ('ACTIVE', 'ON_LEAVE', 'TERMINATED', 'PROBATION')),
    CONSTRAINT employees_type_ck CHECK (employment_type IN ('FULL_TIME', 'PART_TIME', 'CONTRACT', 'INTERN'))
);

COMMENT ON TABLE aihr_employees IS 'Employees table. References with aihr_departments, aihr_jobs, aihr_job_history tables. Contains a self reference.';

CREATE TABLE aihr_job_history (
    employee_id NUMBER(10) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    job_id VARCHAR2(10 CHAR) NOT NULL,
    department_id NUMBER(10),
    CONSTRAINT job_history_pk PRIMARY KEY (employee_id, start_date),
    CONSTRAINT job_history_job_fk FOREIGN KEY (job_id) REFERENCES aihr_jobs(job_id),
    CONSTRAINT job_history_employee_fk FOREIGN KEY (employee_id) REFERENCES aihr_employees(employee_id),
    CONSTRAINT job_history_department_fk FOREIGN KEY (department_id) REFERENCES aihr_departments(department_id),
    CONSTRAINT job_history_dates_ck CHECK (end_date > start_date)
);

COMMENT ON TABLE aihr_job_history IS 'Table that stores job history of the aihr_employees.';

CREATE TABLE aihr_roles (
    role_id NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    role_name VARCHAR2(30 CHAR) NOT NULL,
    description VARCHAR2(255 CHAR),
    CONSTRAINT hr_roles_pk PRIMARY KEY (role_id),
    CONSTRAINT hr_roles_name_uk UNIQUE (role_name)
);

COMMENT ON TABLE aihr_roles IS 'RBAC roles: ROLE_ADMIN, ROLE_HR_SPECIALIST, ROLE_MANAGER, ROLE_EMPLOYEE.';

CREATE TABLE aihr_users (
    user_id NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    employee_id NUMBER(10) NOT NULL,
    username VARCHAR2(60 CHAR) NOT NULL,
    password_hash VARCHAR2(255 CHAR) NOT NULL,
    is_active NUMBER(1) DEFAULT 1 NOT NULL,
    last_login TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT hr_users_pk PRIMARY KEY (user_id),
    CONSTRAINT hr_users_username_uk UNIQUE (username),
    CONSTRAINT hr_users_employee_uk UNIQUE (employee_id),
    CONSTRAINT hr_users_employee_fk FOREIGN KEY (employee_id) REFERENCES aihr_employees(employee_id),
    CONSTRAINT hr_users_active_ck CHECK (is_active IN (0, 1))
);

COMMENT ON TABLE aihr_users IS 'Authentication credentials linked to aihr_employees.';

CREATE TABLE aihr_user_roles (
    user_id NUMBER(10) NOT NULL,
    role_id NUMBER(10) NOT NULL,
    CONSTRAINT hr_user_roles_pk PRIMARY KEY (user_id, role_id),
    CONSTRAINT hr_user_roles_user_fk FOREIGN KEY (user_id) REFERENCES aihr_users(user_id),
    CONSTRAINT hr_user_roles_role_fk FOREIGN KEY (role_id) REFERENCES aihr_roles(role_id)
);

COMMENT ON TABLE aihr_user_roles IS 'Many-to-many mapping between users and roles.';

CREATE TABLE aihr_user_preferences (
    preference_id NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    user_id NUMBER(10) NOT NULL,
    language_code VARCHAR2(10 CHAR) DEFAULT 'en' NOT NULL,
    timezone VARCHAR2(50 CHAR) DEFAULT 'UTC' NOT NULL,
    date_format VARCHAR2(20 CHAR) DEFAULT 'YYYY-MM-DD' NOT NULL,
    currency_code VARCHAR2(3 CHAR) DEFAULT 'USD' NOT NULL,
    number_format VARCHAR2(20 CHAR) DEFAULT '1,000.00' NOT NULL,
    CONSTRAINT hr_user_preferences_pk PRIMARY KEY (preference_id),
    CONSTRAINT hr_user_preferences_user_uk UNIQUE (user_id),
    CONSTRAINT hr_user_preferences_user_fk FOREIGN KEY (user_id) REFERENCES aihr_users(user_id)
);

COMMENT ON TABLE aihr_user_preferences IS 'User-specific NLS/MLS settings (language, timezone, currency, formatting).';

CREATE TABLE aihr_audit_logs (
    audit_id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    table_name VARCHAR2(60 CHAR) NOT NULL,
    record_id VARCHAR2(60 CHAR) NOT NULL,
    action VARCHAR2(10 CHAR) NOT NULL,
    old_value CLOB,
    new_value CLOB,
    changed_by NUMBER(10),
    changed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT hr_audit_logs_pk PRIMARY KEY (audit_id),
    CONSTRAINT hr_audit_logs_user_fk FOREIGN KEY (changed_by) REFERENCES aihr_users(user_id),
    CONSTRAINT hr_audit_logs_action_ck CHECK (action IN ('INSERT', 'UPDATE', 'DELETE')),
    CONSTRAINT hr_audit_logs_old_json_ck CHECK (old_value IS JSON),
    CONSTRAINT hr_audit_logs_new_json_ck CHECK (new_value IS JSON)
);

COMMENT ON TABLE aihr_audit_logs IS 'Audit trail capturing all changes to critical tables.';

CREATE TABLE aihr_employee_documents (
    document_id NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    employee_id NUMBER(10) NOT NULL,
    document_name VARCHAR2(255 CHAR) NOT NULL,
    document_category VARCHAR2(50 CHAR) NOT NULL,
    file_path VARCHAR2(500 CHAR) NOT NULL,
    file_type VARCHAR2(20 CHAR) NOT NULL,
    file_size_bytes NUMBER(19),
    uploaded_by NUMBER(10),
    uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT hr_employee_documents_pk PRIMARY KEY (document_id),
    CONSTRAINT hr_employee_documents_emp_fk FOREIGN KEY (employee_id) REFERENCES aihr_employees(employee_id),
    CONSTRAINT hr_employee_documents_user_fk FOREIGN KEY (uploaded_by) REFERENCES aihr_users(user_id)
);

COMMENT ON TABLE aihr_employee_documents IS 'Digital documents attached to employee profiles.';
COMMENT ON COLUMN aihr_employee_documents.document_category IS 'e.g. Contract, ID, Certificate, Payslip, Other';

CREATE TABLE aihr_idempotency_keys (
    idempotency_key VARCHAR2(64 CHAR) NOT NULL,
    endpoint VARCHAR2(100 CHAR) NOT NULL,
    response_status NUMBER(10) NOT NULL,
    response_body CLOB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    CONSTRAINT hr_idempotency_keys_pk PRIMARY KEY (idempotency_key),
    CONSTRAINT hr_idempotency_keys_body_json_ck CHECK (response_body IS JSON)
);

COMMENT ON TABLE aihr_idempotency_keys IS 'Stores idempotency keys and cached responses for mutation requests.';

CREATE TABLE aihr_notifications (
    notification_id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL,
    recipient_user_id NUMBER(10) NOT NULL,
    notification_type VARCHAR2(20 CHAR) NOT NULL,
    title VARCHAR2(255 CHAR) NOT NULL,
    message CLOB,
    reference_table VARCHAR2(60 CHAR),
    reference_id VARCHAR2(60 CHAR),
    is_read NUMBER(1) DEFAULT 0 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT hr_notifications_pk PRIMARY KEY (notification_id),
    CONSTRAINT hr_notifications_user_fk FOREIGN KEY (recipient_user_id) REFERENCES aihr_users(user_id),
    CONSTRAINT hr_notifications_type_ck CHECK (notification_type IN ('PROBATION_ALERT', 'CONTRACT_EXPIRY', 'ACTION_COMPLETE', 'SYSTEM')),
    CONSTRAINT hr_notifications_read_ck CHECK (is_read IN (0, 1))
);

COMMENT ON TABLE aihr_notifications IS 'System notifications and alerts for users.';

