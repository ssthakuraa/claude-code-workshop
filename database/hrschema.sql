CREATE TABLE aihr_regions (
    region_id integer NOT NULL,
    region_name varchar(25),
    CONSTRAINT regions_pk PRIMARY KEY (region_id)
);

COMMENT ON TABLE aihr_regions IS 'Regions table that contains region numbers and names. References with the Countries table.';

CREATE TABLE aihr_countries (
    country_id char(2) NOT NULL,
    country_name varchar(60),
    region_id integer,
    CONSTRAINT countries_pk PRIMARY KEY (country_id),
    CONSTRAINT countries_region_fk FOREIGN KEY (region_id) REFERENCES aihr_regions(region_id)
);

COMMENT ON TABLE aihr_countries IS 'Country table. References with the aihr_locations table.';

CREATE TABLE aihr_locations (
    location_id integer NOT NULL,
    street_address varchar(40),
    postal_code varchar(12),
    city varchar(30) NOT NULL,
    state_province varchar(25),
    country_id char(2),
    CONSTRAINT locations_pk PRIMARY KEY (location_id),
    CONSTRAINT locations_country_fk FOREIGN KEY (country_id) REFERENCES aihr_countries(country_id)
);

COMMENT ON TABLE aihr_locations IS 'Locations table that contains specific address of a specific office, warehouse, and/or production site of a company.';

CREATE TABLE aihr_departments (
    department_id integer NOT NULL,
    department_name varchar(30) NOT NULL,
    manager_id integer,
    location_id integer,
    parent_department_id integer,
    deleted_at timestamp,
    CONSTRAINT departments_pk PRIMARY KEY (department_id),
    CONSTRAINT departments_location_fk FOREIGN KEY (location_id) REFERENCES aihr_locations(location_id),
    CONSTRAINT dept_parent_fk FOREIGN KEY (parent_department_id) REFERENCES aihr_departments(department_id)
);

COMMENT ON TABLE aihr_departments IS 'Departments table that shows details of departments where employees work.';

CREATE TABLE aihr_jobs (
    job_id varchar(10) NOT NULL,
    job_title varchar(35) NOT NULL,
    min_salary integer,
    max_salary integer,
    CONSTRAINT jobs_pk PRIMARY KEY (job_id)
);

COMMENT ON TABLE aihr_jobs IS 'Jobs table with job titles and salary ranges. References with aihr_employees and aihr_job_history table.';

CREATE TABLE aihr_pay_grades (
    pay_grade_id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    grade_code varchar(20) NOT NULL,
    grade_name varchar(60) NOT NULL,
    min_salary numeric(10,2) NOT NULL,
    max_salary numeric(10,2) NOT NULL,
    currency_code varchar(3) DEFAULT 'USD' NOT NULL,
    display_order integer NOT NULL,
    description varchar(255),
    is_active smallint DEFAULT 1 NOT NULL,
    created_at timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT aihr_pay_grades_pk PRIMARY KEY (pay_grade_id),
    CONSTRAINT aihr_pay_grades_code_uk UNIQUE (grade_code),
    CONSTRAINT aihr_pay_grades_range_ck CHECK (max_salary >= min_salary),
    CONSTRAINT aihr_pay_grades_active_ck CHECK (is_active IN (0, 1))
);

COMMENT ON TABLE aihr_pay_grades IS 'Lab-only reference table for salary bands and pay-grade exercises. No backend resource or service is planned in the current phase.';

CREATE TABLE aihr_assessment_cycles (
    cycle_code varchar(30) NOT NULL,
    default_label varchar(120) NOT NULL,
    period_type varchar(20) NOT NULL,
    start_date date NOT NULL,
    end_date date NOT NULL,
    cycle_status varchar(20) DEFAULT 'PLANNED' NOT NULL,
    display_order integer NOT NULL,
    is_active smallint DEFAULT 1 NOT NULL,
    created_at timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT aihr_assessment_cycles_pk PRIMARY KEY (cycle_code),
    CONSTRAINT aihr_assessment_cycles_period_ck CHECK (period_type IN ('QUARTER', 'HALF', 'ANNUAL')),
    CONSTRAINT aihr_assessment_cycles_status_ck CHECK (cycle_status IN ('PLANNED', 'OPEN', 'CLOSED')),
    CONSTRAINT aihr_assessment_cycles_date_ck CHECK (end_date >= start_date),
    CONSTRAINT aihr_assessment_cycles_display_uk UNIQUE (display_order),
    CONSTRAINT aihr_assessment_cycles_active_ck CHECK (is_active IN (0, 1))
);

COMMENT ON TABLE aihr_assessment_cycles IS 'Maintained assessment-cycle catalog for performance review windows and future assessment workflows.';
COMMENT ON COLUMN aihr_assessment_cycles.cycle_code IS 'Stable business key such as FY2026-Q1 or FY2026-H1.';
COMMENT ON COLUMN aihr_assessment_cycles.default_label IS 'Default English label used when no translation row exists.';
COMMENT ON COLUMN aihr_assessment_cycles.period_type IS 'Review cadence classification: QUARTER, HALF, or ANNUAL.';
COMMENT ON COLUMN aihr_assessment_cycles.cycle_status IS 'Operational state for setup and downstream assessment workflows.';

CREATE TABLE aihr_employees (
    employee_id integer GENERATED BY DEFAULT AS IDENTITY (START WITH 207) NOT NULL,
    first_name varchar(20),
    last_name varchar(25) NOT NULL,
    email varchar(100) NOT NULL,
    phone_number varchar(20),
    hire_date date NOT NULL,
    job_id varchar(10) NOT NULL,
    salary numeric(8,2),
    commission_pct numeric(3,2),
    manager_id integer,
    department_id integer,
    employment_status varchar(20) DEFAULT 'ACTIVE' NOT NULL,
    employment_type varchar(20) DEFAULT 'FULL_TIME' NOT NULL,
    contract_end_date date,
    deleted_at timestamp,
    CONSTRAINT employees_pk PRIMARY KEY (employee_id),
    CONSTRAINT employees_email_uk UNIQUE (email),
    CONSTRAINT employees_department_fk FOREIGN KEY (department_id) REFERENCES aihr_departments(department_id),
    CONSTRAINT employees_job_fk FOREIGN KEY (job_id) REFERENCES aihr_jobs(job_id),
    CONSTRAINT employees_manager_fk FOREIGN KEY (manager_id) REFERENCES aihr_employees(employee_id),
    CONSTRAINT employees_salary_ck CHECK (salary > 0),
    CONSTRAINT employees_status_ck CHECK (employment_status IN ('ACTIVE', 'ON_LEAVE', 'TERMINATED', 'PROBATION')),
    CONSTRAINT employees_type_ck CHECK (employment_type IN ('FULL_TIME', 'PART_TIME', 'CONTRACT', 'INTERN'))
);

COMMENT ON TABLE aihr_employees IS 'Employees table. References with aihr_departments, aihr_jobs, aihr_job_history tables. Contains a self reference.';

CREATE TABLE aihr_job_history (
    employee_id integer NOT NULL,
    start_date date NOT NULL,
    end_date date NOT NULL,
    job_id varchar(10) NOT NULL,
    department_id integer,
    CONSTRAINT job_history_pk PRIMARY KEY (employee_id, start_date),
    CONSTRAINT job_history_job_fk FOREIGN KEY (job_id) REFERENCES aihr_jobs(job_id),
    CONSTRAINT job_history_employee_fk FOREIGN KEY (employee_id) REFERENCES aihr_employees(employee_id),
    CONSTRAINT job_history_department_fk FOREIGN KEY (department_id) REFERENCES aihr_departments(department_id),
    CONSTRAINT job_history_dates_ck CHECK (end_date > start_date)
);

COMMENT ON TABLE aihr_job_history IS 'Table that stores job history of the aihr_employees.';

CREATE TABLE aihr_roles (
    role_id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    role_name varchar(30) NOT NULL,
    description varchar(255),
    CONSTRAINT hr_roles_pk PRIMARY KEY (role_id),
    CONSTRAINT hr_roles_name_uk UNIQUE (role_name)
);

COMMENT ON TABLE aihr_roles IS 'RBAC roles: ROLE_ADMIN, ROLE_HR_SPECIALIST, ROLE_MANAGER, ROLE_EMPLOYEE.';

CREATE TABLE aihr_users (
    user_id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    employee_id integer NOT NULL,
    username varchar(60) NOT NULL,
    password_hash varchar(255) NOT NULL,
    is_active smallint DEFAULT 1 NOT NULL,
    last_login timestamp,
    created_at timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT hr_users_pk PRIMARY KEY (user_id),
    CONSTRAINT hr_users_username_uk UNIQUE (username),
    CONSTRAINT hr_users_employee_uk UNIQUE (employee_id),
    CONSTRAINT hr_users_employee_fk FOREIGN KEY (employee_id) REFERENCES aihr_employees(employee_id),
    CONSTRAINT hr_users_active_ck CHECK (is_active IN (0, 1))
);

COMMENT ON TABLE aihr_users IS 'Authentication credentials linked to aihr_employees.';

CREATE TABLE aihr_user_roles (
    user_id integer NOT NULL,
    role_id integer NOT NULL,
    CONSTRAINT hr_user_roles_pk PRIMARY KEY (user_id, role_id),
    CONSTRAINT hr_user_roles_user_fk FOREIGN KEY (user_id) REFERENCES aihr_users(user_id),
    CONSTRAINT hr_user_roles_role_fk FOREIGN KEY (role_id) REFERENCES aihr_roles(role_id)
);

COMMENT ON TABLE aihr_user_roles IS 'Many-to-many mapping between users and roles.';

CREATE TABLE aihr_user_preferences (
    preference_id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id integer NOT NULL,
    language_code varchar(10) DEFAULT 'en' NOT NULL,
    timezone varchar(50) DEFAULT 'UTC' NOT NULL,
    date_format varchar(20) DEFAULT 'YYYY-MM-DD' NOT NULL,
    currency_code varchar(3) DEFAULT 'USD' NOT NULL,
    number_format varchar(20) DEFAULT '1,000.00' NOT NULL,
    CONSTRAINT hr_user_preferences_pk PRIMARY KEY (preference_id),
    CONSTRAINT hr_user_preferences_user_uk UNIQUE (user_id),
    CONSTRAINT hr_user_preferences_user_fk FOREIGN KEY (user_id) REFERENCES aihr_users(user_id)
);

COMMENT ON TABLE aihr_user_preferences IS 'User-specific NLS/MLS settings (language, timezone, currency, formatting).';

CREATE TABLE aihr_employee_assessments (
    assessment_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    employee_id integer NOT NULL,
    cycle_code varchar(30) NOT NULL,
    review_status varchar(20) DEFAULT 'DRAFT' NOT NULL,
    goal_completion_pct numeric(5,2),
    competency_score numeric(4,2),
    manager_feedback text,
    employee_reflection text,
    next_cycle_plan text,
    reviewer_user_id integer NOT NULL,
    submitted_at timestamp,
    created_at timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT aihr_employee_assessments_pk PRIMARY KEY (assessment_id),
    CONSTRAINT aihr_employee_assessments_employee_fk FOREIGN KEY (employee_id) REFERENCES aihr_employees(employee_id),
    CONSTRAINT aihr_employee_assessments_cycle_fk FOREIGN KEY (cycle_code) REFERENCES aihr_assessment_cycles(cycle_code),
    CONSTRAINT aihr_employee_assessments_reviewer_fk FOREIGN KEY (reviewer_user_id) REFERENCES aihr_users(user_id),
    CONSTRAINT aihr_employee_assessments_cycle_uk UNIQUE (employee_id, cycle_code),
    CONSTRAINT aihr_employee_assessments_goal_pct_ck CHECK (goal_completion_pct IS NULL OR goal_completion_pct BETWEEN 0 AND 100),
    CONSTRAINT aihr_employee_assessments_comp_score_ck CHECK (competency_score IS NULL OR competency_score BETWEEN 0 AND 5),
    CONSTRAINT aihr_employee_assessments_status_ck CHECK (review_status IN ('DRAFT', 'SUBMITTED', 'FINAL'))
);

COMMENT ON TABLE aihr_employee_assessments IS 'Employee self-service assessment records keyed by employee and assessment cycle.';
COMMENT ON COLUMN aihr_employee_assessments.cycle_code IS 'Assessment-cycle business key such as FY2026-H1.';
COMMENT ON COLUMN aihr_employee_assessments.review_status IS 'Employee workflow state: DRAFT, SUBMITTED, or FINAL.';
COMMENT ON COLUMN aihr_employee_assessments.goal_completion_pct IS 'Optional draft-safe progress metric expressed as a percentage from 0 to 100.';
COMMENT ON COLUMN aihr_employee_assessments.competency_score IS 'Optional draft-safe competency score from 0.00 to 5.00.';
COMMENT ON COLUMN aihr_employee_assessments.manager_feedback IS 'Reviewer feedback shown read-only to the employee when available.';
COMMENT ON COLUMN aihr_employee_assessments.employee_reflection IS 'Employee-authored reflection for the cycle submission.';
COMMENT ON COLUMN aihr_employee_assessments.next_cycle_plan IS 'Employee-authored forward plan for the next cycle.';
COMMENT ON COLUMN aihr_employee_assessments.reviewer_user_id IS 'Assigned reviewer account, typically the employee manager or an HR fallback.';

