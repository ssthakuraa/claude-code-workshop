CREATE TABLE aihr_audit_logs (
    audit_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    table_name varchar(60) NOT NULL,
    record_id varchar(60) NOT NULL,
    action varchar(10) NOT NULL,
    old_value jsonb,
    new_value jsonb,
    changed_by integer,
    changed_at timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT hr_audit_logs_pk PRIMARY KEY (audit_id),
    CONSTRAINT hr_audit_logs_user_fk FOREIGN KEY (changed_by) REFERENCES aihr_users(user_id),
    CONSTRAINT hr_audit_logs_action_ck CHECK (action IN ('INSERT', 'UPDATE', 'DELETE'))
);

COMMENT ON TABLE aihr_audit_logs IS 'Audit trail capturing all changes to critical tables.';

